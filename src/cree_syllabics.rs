/// Look up a syllabic entry by Unicode codepoint across both main and extended blocks.
#[inline]
pub fn by_codepoint(cp: u32) -> Option<&'static SyllabicEntry> {
    UCAS_MAIN
        .iter()
        .chain(UCAS_EXTENDED.iter())
        .find(|e| e.0 == cp)
}

/// Look up a syllabic entry by the character itself.
#[inline]
pub fn by_char(ch: char) -> Option<&'static SyllabicEntry> {
    by_codepoint(ch as u32)
}

/// Check if a character falls within any UCAS block (main or extended).
#[inline]
pub fn is_syllabic(ch: char) -> bool {
    let cp = ch as u32;
    (0x1400..=0x167F).contains(&cp) || (0x18B0..=0x18FF).contains(&cp)
}

#[cfg(test)]
mod tests {
    use super::*;

    // [BOARD:CREE-TABLE-TRIPLE-ORACLE] 2026-07-28 defect fix pinned: the table
    // duplicated 0x1449 onto 0x1549, stamped Y-names on the H/HK/Q block, and
    // omitted the true Y-series. Sources: disk grep + gemini-3.1-flash-lite +
    // unicode.org list-unicodeset (three oracles, unanimous).
    #[test]
    fn no_codepoint_appears_twice() {
        let mut seen = std::collections::HashSet::new();
        for (cp, _, name) in UCAS_MAIN.iter().chain(UCAS_EXTENDED.iter()) {
            assert!(seen.insert(*cp), "duplicate codepoint U+{cp:04X} ({name})");
        }
    }

    #[test]
    fn y_series_lives_in_its_true_block() {
        for (cp, ch, name) in [
            (0x1526, 'ᔦ', "CANADIAN SYLLABICS YE"),
            (0x152A, 'ᔪ', "CANADIAN SYLLABICS YO"),
            (0x152D, 'ᔭ', "CANADIAN SYLLABICS YA"),
            (0x1540, 'ᕀ', "CANADIAN SYLLABICS WEST-CREE Y"),
        ] {
            let e = by_codepoint(cp).unwrap_or_else(|| panic!("U+{cp:04X} absent"));
            assert_eq!((e.1, e.2), (ch, name), "U+{cp:04X}");
        }
    }

    #[test]
    fn hk_and_q_block_no_longer_wears_y_names() {
        assert_eq!(by_codepoint(0x157D).unwrap().2, "CANADIAN SYLLABICS HK");
        assert_eq!(by_codepoint(0x157F).unwrap().2, "CANADIAN SYLLABICS QI");
        assert_eq!(by_codepoint(0x1549).unwrap().1, 'ᕉ', "0x1549 is ROO, not a P dup");
    }
}
